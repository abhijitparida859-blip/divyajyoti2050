    statusHeadlineOr = 'ଥର୍ମୋସ୍ଫିୟର୍: ଆନ୍ତର୍ଜାତୀୟ ମହାକାଶ ଷ୍ଟେସନ୍ (ISS 408 km) ଓ ଚିତ୍ତାକର୍ଷକ ମେରୁପ୍ରଭା (Aurora)।';
